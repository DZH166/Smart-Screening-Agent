class Workflow:
    def __init__(self, service, client, owner, provider):
        self.service, self.client, self.owner, self.provider = service, client, owner, provider
        self.patterns = [self.upload(png(shape, color, marker=index), f'controlled-{index}')
                         for index, (shape, color) in enumerate((((80, 160), '#c76587'),
                                                                ((260, 70), '#437da3'),
                                                                ((120, 120), '#568958')))]
        self.background = self.upload(png((512, 512), '#e7edf2', pattern=False), 'controlled-background', 'background')
        self.selection = dict(asset_ids=[row['id'] for row in self.patterns], background_id=self.background['id'],
                              template_id='single', background_tone='original', design_density='balanced')

    def upload(self, value, name, kind='pattern'):
        return ok(self.client.post('/api/assets', files={'file': (name + '.png', value, 'image/png')},
                                   data={'kind': kind, 'name': name}))

    def create(self):
        return ok(self.client.post('/api/designs', json={'name': 'Explicit synthetic loop workflow'}))

    def get(self, design):
        return ok(self.client.get(f'/api/designs/{design["id"]}'))

    def work(self, job):
        assert self.service.run_once()
        return ok(self.client.get(f'/api/jobs/{job["id"]}'))

    def generate(self, selection=None, **options):
        design = self.create()
        body = dict(selection or self.selection, idempotency_key=str(uuid4()), **options)
        job = ok(self.client.post(f'/api/designs/{design["id"]}/generate', json=body))
        result = self.work(job)
        assert result['status'] == 'SUCCEEDED', result
        return self.get(design)

    def submit_refine(self, design, *, selection=None, prompt='Explicit synthetic refinement', key=None):
        """Restore an accepted historical recipe, then read its real receipt."""
        body = dict(idempotency_key=key or str(uuid4()), base_version_id=design['current_version_id'], prompt=prompt)
        if selection is not None:
            body['selection'] = selection
        return recover_legacy_refinement(self.client, self.service, f'/api/designs/{design["id"]}/refinements', json=body)

    def refine(self, design, **options):
        result = self.work(ok(self.submit_refine(design, **options)))
        return result, self.get(design)

    def download(self, version):
        response = self.client.get(version['download_url'])
        assert response.status_code == 200, response.text
        return response.content


