@pytest.mark.parametrize('height,dpi', ((240, 96), (520, 300)))
def test_new_engine_worker_binds_inputs_to_saved_download_and_preserves_parent(workflow, height, dpi):
    from ribbon_backend import loop_pipeline_v3

    workflow.service.save_profile(
        dict(name='current worker', width=1280, height=height, dpi=dpi, format='PNG', is_demo=True)
    )
    initial = workflow.generate()
    first = current(initial)
    data = workflow.download(first)
    snapshot = first['snapshot']
    assert snapshot['layout_engine'] == loop_pipeline_v3.ENGINE
    loop_pipeline_v3.validate_binding(snapshot, hashlib.sha256(data).hexdigest())
    with Image.open(BytesIO(data)) as png_file:
        assert png_file.size == (snapshot['loop_layout']['period_px'], height)
        assert abs(png_file.info['dpi'][0] - dpi) < 1
    assert [item['id'] for item in snapshot['loop']['inputs']] == [
        *snapshot['asset_refs'],
        snapshot['background_ref'],
    ]
    selection = {**workflow.selection, 'design_density': 'airy'}
    done, current_design = workflow.refine(initial, selection=selection, prompt='应用所选配置')
    assert done['status'] == 'SUCCEEDED', done
    assert current_design['successful_refinement_count'] == 1
    newer = current(current_design)
    assert newer['parent_version_id'] == first['id']
    assert workflow.download(first) == data
    assert workflow.download(newer) != data


def assert_bound(env, version, *, height, dpi):
    saved = version['snapshot']
    raw = env.download(version)
    with Image.open(BytesIO(raw)) as image:
        assert image.size == (saved['output_profile']['width'], height)
        assert abs(image.info['dpi'][0] - dpi) < 1
    assert saved['layout_engine'] == ENGINE
    assert saved['loop']['width'] == saved['output_profile']['width']
    assert saved['loop']['height'] == saved['output_profile']['height'] == height
    assert saved['loop']['output_sha256'] == hashlib.sha256(raw).hexdigest()
    assert saved['loop']['production_verified'] is False
    assert saved['loop']['geometry']['passed'] is True
    assert saved['loop']['verification_scope'] == 'period_construction_and_multiscale_pixel_checks'
    loop_pipeline.validate_binding(saved, hashlib.sha256(raw).hexdigest())
    return raw


