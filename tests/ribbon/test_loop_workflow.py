@pytest.mark.parametrize('corruption', ('sha', 'width', 'geometry_signature', 'geometry_failed',
                                       'layout_geometry_failed', 'background_failed', 'background_wrap_failed',
                                       'final_wrap_failed', 'empty_review', 'missing_geometry', 'nonboolean_background',
                                       'false_coverage_both_reports', 'geometry_errors_both_reports',
                                       'placement_count_both_reports', 'background_production_claim'))
def test_immutable_loop_binding_rejects_forged_or_inconsistent_verification_reports(env, corruption):
    design = env.generate()
    version = current(design)
    saved = deepcopy(version['snapshot'])
    raw = env.download(version)
    sha = hashlib.sha256(raw).hexdigest()
    loop_pipeline.validate_binding(saved, sha)
    if corruption == 'sha': saved['loop']['output_sha256'] = '0' * 64
    elif corruption == 'width': saved['loop']['width'] += 1
    elif corruption == 'geometry_signature': saved['loop_layout']['input_signature'] = '0' * 64
    elif corruption == 'geometry_failed': saved['loop']['geometry']['passed'] = False
    elif corruption == 'layout_geometry_failed': saved['loop_layout']['verification']['passed'] = False
    elif corruption == 'background_failed':
        saved['loop']['background']['passed'] = False
        saved['loop']['background']['status'] = 'needs_review'
        saved['loop']['status'] = 'checked'; saved['loop']['issues'] = []
    elif corruption == 'background_wrap_failed':
        saved['loop']['background_wrap']['passed'] = False
        saved['loop']['status'] = 'checked'; saved['loop']['issues'] = []
    elif corruption == 'final_wrap_failed':
        saved['loop']['final_wrap']['passed'] = False
        saved['loop']['status'] = 'checked'; saved['loop']['issues'] = []
    elif corruption == 'empty_review': saved['loop']['status'] = 'needs_review'; saved['loop']['issues'] = []
    elif corruption == 'missing_geometry': saved['loop'].pop('geometry')
    elif corruption == 'nonboolean_background': saved['loop']['background']['passed'] = 'true'
    elif corruption == 'false_coverage_both_reports':
        saved['loop']['geometry']['source_coverage_complete'] = False
        saved['loop_layout']['verification']['source_coverage_complete'] = False
    elif corruption == 'geometry_errors_both_reports':
        saved['loop']['geometry']['errors'] = ['Explicit synthetic construction failure']
        saved['loop_layout']['verification']['errors'] = ['Explicit synthetic construction failure']
    elif corruption == 'placement_count_both_reports':
        saved['loop']['geometry']['placement_count'] += 1
        saved['loop_layout']['verification']['placement_count'] += 1
    elif corruption == 'background_production_claim': saved['loop']['background']['production_verified'] = True
    with pytest.raises(ValueError):
        loop_pipeline.validate_binding(saved, sha)
    assert env.download(version) == raw
    assert env.get(design)['successful_refinement_count'] == 0


@pytest.mark.parametrize('corruption', ('checked_report', 'input_sha', 'input_order', 'missing_inputs'))
def test_recovered_tampered_report_or_inputs_cannot_commit_or_charge(env, monkeypatch, corruption):
    initial = env.generate()
    original = env.download(current(initial))
    env.provider.operations = [{'type': 'parameters', 'values': {'scale': .69}}]
    complete = env.service.complete_job
    monkeypatch.setattr(env.service, 'complete_job', defer_commit)
    submitted = ok(env.submit_refine(initial))
    assert env.work(submitted)['status'] == 'RECONCILING'
    with env.service.db.transaction() as db:
        artifact = json.loads(db.execute('SELECT artifact_json FROM jobs WHERE id=?', (submitted['id'],)).fetchone()[0])
        if corruption == 'checked_report':
            artifact['snapshot']['loop']['background']['passed'] = False
            artifact['snapshot']['loop']['status'] = 'checked'
            artifact['snapshot']['loop']['issues'] = []
        elif corruption == 'input_sha':
            artifact['snapshot']['loop']['inputs'][0]['sha256'] = '0' * 64
        elif corruption == 'input_order':
            artifact['snapshot']['loop']['inputs'].reverse()
        elif corruption == 'missing_inputs':
            artifact['snapshot']['loop'].pop('inputs')
