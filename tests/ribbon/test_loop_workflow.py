def test_scale_spacing_recompute_width_and_parent_rollback_preserves_exact_downloads(env):
    # Hide the texture with a solid override so foreground spacing, rather than
    # an integer texture-period multiple, determines the measurable unit width.
    original = env.generate()
    env.provider.operations = [{'type': 'parameters', 'values': {'background_color': '#E7EDF2', 'spacing': 3.0}}]
    job, spaced = env.refine(original)
    assert job['status'] == 'SUCCEEDED', job
    restored = ok(env.client.post(f'/api/designs/{spaced["id"]}/rollback',
                                  json={'expected_version_id': spaced['current_version_id']}))
    assert restored['current_version_id'] == original['current_version_id']
    assert restored['successful_refinement_count'] == 1
    assert env.download(current(restored)) == env.download(current(original))
    env.provider.operations = [{'type': 'parameters', 'values': {'background_color': '#E7EDF2', 'scale': .64}}]
    job, scaled = env.refine(restored)
    assert job['status'] == 'SUCCEEDED', job
    versions = [current(design) for design in (original, spaced, scaled)]
    widths = [version['snapshot']['output_profile']['width'] for version in versions]
    assert widths[1] > widths[0] and widths[2] < widths[0]
    originals = {version['id']: assert_bound(env, version, height=240, dpi=96) for version in versions}
    assert len({hashlib.sha256(raw).hexdigest() for raw in originals.values()}) == 3
    assert scaled['successful_refinement_count'] == 2
    assert versions[2]['parent_version_id'] == versions[1]['parent_version_id'] == versions[0]['id']
    rolled = ok(env.client.post(f'/api/designs/{scaled["id"]}/rollback', json={'expected_version_id': versions[2]['id']}))
    assert rolled['current_version_id'] == versions[0]['id'] and rolled['successful_refinement_count'] == 2
    assert env.download(current(rolled)) == originals[versions[0]['id']]
    with env.service.db.connect() as db:
        assert db.execute('SELECT COUNT(*) FROM quota_events WHERE design_id=?', (scaled['id'],)).fetchone()[0] == 2
    assert env.client.post(f'/api/designs/{rolled["id"]}/refinements', json={}).status_code == 410


