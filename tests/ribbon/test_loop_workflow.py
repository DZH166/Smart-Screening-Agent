def png(size, color, *, pattern=True, marker=0):
    out = BytesIO()
    with Image.new('RGBA', (size[0] + 24, size[1] + 32) if pattern else size,
                   (0, 0, 0, 0) if pattern else color) as image:
        if pattern:
            draw = ImageDraw.Draw(image)
            draw.rectangle((12, 16, size[0] + 11, size[1] + 15), fill=color)
            draw.rectangle((12, 16, min(size[0] + 11, 20 + marker), min(size[1] + 15, 24)), fill='#ffff00')
            image.putpixel((size[0] + 11, size[1] + 15), (10, 15, 20, 255))
        image.save(out, format='PNG')
    return out.getvalue()


class CountingSyntheticProvider(SyntheticProvider):
    """Explicit fixture: controlled plan, aspect edits and 2048px draft."""
    name = 'test'

    def __init__(self):
        self.plan_calls = []
        self.edit_calls = []
        self.draft_calls = []
        self.operations = None
        self.edit_size = None
        self.draft_failure = None

    def plan(self, prompt, snapshot, assets):
        self.plan_calls.append(dict(prompt=prompt, snapshot=deepcopy(snapshot)))
        if self.operations is None:
            return super().plan(prompt, snapshot, assets)
        return dict(summary='Explicit synthetic workflow plan', operations=deepcopy(self.operations), is_demo=True)

    def edit_image(self, prompt, source, output, kind):
        self.edit_calls.append(dict(kind=kind, source=Path(source).read_bytes()))
        if self.edit_size is None:
            return super().edit_image(prompt, source, output, kind)
        output.write_bytes(png(self.edit_size, '#654bc1'))
        return dict(model='explicit-synthetic-aspect-editor', is_demo=True, usage={'generated_images': 1})

    def generate_draft_background(self, patterns, background, reference, output, **options):
        self.draft_calls.append(dict(patterns=[Path(path).read_bytes() for path in patterns],
                                     background=Path(background).read_bytes(), reference=reference,
                                     options=deepcopy(options)))
        if self.draft_failure:
            raise self.draft_failure
        with Image.new('RGBA', (2048, 2048), '#e7edf2') as image:
            image.save(output, format='PNG')
        return dict(model='explicit-synthetic-draft-background', is_demo=True, usage={'generated_images': 1})


